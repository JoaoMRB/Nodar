    public static string Lookup(string mac)
    {
        if (string.IsNullOrWhiteSpace(mac))
        {
            return "Desconhecido";
        }

        var normalized = NormalizeMac(mac);
        var prefix = normalized.Length >= 8 ? normalized[..8] : normalized;
        return Vendors.TryGetValue(prefix, out var vendor) ? vendor : "Desconhecido";
    }

    public static string GetDeviceType(string vendor, string hostname)
    {
        vendor ??= "";
        hostname ??= "";
        var text = $"{vendor} {hostname}".ToLowerInvariant();
        var host = hostname.ToLowerInvariant();

        // Pistas fortes no hostname (o fabricante por OUI falha muitas vezes, sobretudo com MACs aleatórios).
        if (ContainsAny(host, "googletv", "chromecast", "androidtv", "bravia", "roku", "firetv", "appletv", "smarttv", "-tv", "tv-", "webos", "tizen"))
            return "TV";
        if (ContainsAny(text, "epson", "brother", "canon", "printer", "laserjet", "officejet", "deskjet", "kyocera", "lexmark", "xerox")
            || host.StartsWith("hp") || host.StartsWith("npi"))
            return "Impressora";
        if (ContainsAny(host, "iphone", "ipad", "android", "galaxy", "pixel", "redmi", "xiaomi", "huawei", "oneplus", "phone"))
            return host.Contains("iphone") || host.Contains("ipad") ? "Apple" : "Telemóvel";
        if (ContainsAny(host, "playstation", "ps4", "ps5", "xbox", "nintendo", "switch"))
            return "Consola";
        if (ContainsAny(host, "camera", "cam-", "ipcam", "hikvision", "dahua", "reolink", "ring-"))
            return "Câmara";

        if (vendor.Equals("Apple", StringComparison.OrdinalIgnoreCase)
            || text.Contains("apple")
            || text.Contains("iphone")
            || text.Contains("ipad")
            || text.Contains("macbook")
            || text.Contains("ios"))
            return "Apple";

        if (vendor.Equals("Samsung", StringComparison.OrdinalIgnoreCase)
            || text.Contains("samsung")
            || text.Contains("galaxy")
            || text.Contains("android")
            || text.Contains("sm-")
            || text.Contains("galaxy"))
            return "Telemóvel";
        if (text.Contains("amazon") || text.Contains("echo") || text.Contains("fire"))
            return "Smart Home";
        if (text.Contains("tp-link") || text.Contains("netgear") || text.Contains("d-link") || text.Contains("ubiquiti") || text.Contains("router") || text.Contains("gateway"))
            return "Router";
        if (text.Contains("raspberry") || text.Contains("server") || text.Contains("nas"))
            return "Servidor";
        if (text.Contains("vmware") || text.Contains("virtualbox") || text.Contains("hyper-v") || text.Contains("qemu"))
            return "Virtual";
        if (text.Contains("philips") || text.Contains("nest") || text.Contains("hue"))
            return "Smart Home";
        if (text.Contains("microsoft") || text.Contains("desktop") || text.Contains("pc") || text.Contains("laptop"))
            return "Computador";

        return "Dispositivo";
    }

    private static bool ContainsAny(string text, params string[] needles) =>
        needles.Any(n => text.Contains(n, StringComparison.Ordinal));

    public static string NormalizeMac(string mac)
    {
        var parts = mac.ToUpperInvariant()
            .Replace('-', ':')
            .Split(':', StringSplitOptions.RemoveEmptyEntries);

        if (parts.Length >= 6)
        {
            return string.Join(':', parts.Take(6));
        }

        return mac.ToUpperInvariant();
    }
